import 'dart0:convert';
import 'dart:io';
import 'package:shelf/shelf.dart';
import 'package:shelf/shelf_io.dart' as io;
import 'package:shelf_router/shelf_router.dart';
import 'package:network_info_plus/network_info_plus.dart';
import 'package:http/http.dart' as http;

class LanService {
  static HttpServer? _server;
  static String? serverIp;
  static const int port = 8080;

  // Lấy IP Wi-Fi của máy
  static Future<String?> getLocalIp() async {
    final info = NetworkInfo();
    serverIp = await info.getWifiIP();
    return serverIp;
  }

  // Khởi chạy Server
  static Future<void> startServer(
    List<Map<String, dynamic>> orders,
    Function(Map<String, dynamic>) onNewOrder,
  ) async {
    final router = Router();

    router.get('/orders', (Request request) {
      return Response.ok(
        jsonEncode(orders),
        headers: {'content-type': 'application/json'},
      );
    });

    router.post('/orders', (Request request) async {
      final payload = await request.readAsString();
      final newOrder = jsonDecode(payload) as Map<String, dynamic>;
      onNewOrder(newOrder);
      return Response.ok(
        jsonEncode({'status': 'success'}),
        headers: {'content-type': 'application/json'},
      );
    });

    _server = await io.serve(router.call, InternetAddress.anyIPv4, port);
    await getLocalIp();
  }

  // Tắt Server
  static Future<void> stopServer() async {
    await _server?.close(force: true);
    _server = null;
  }

  // Máy trạm gửi đơn về Máy chủ
  static Future<bool> sendOrderToHost(String hostIp, Map<String, dynamic> order) async {
    try {
      final response = await http.post(
        Uri.parse('http://$hostIp:$port/orders'),
        headers: {'content-type': 'application/json'},
        body: jsonEncode(order),
      );
      return response.statusCode == 200;
    } catch (e) {
      return false;
    }
  }
}
